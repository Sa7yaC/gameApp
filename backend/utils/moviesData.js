/**
 * Filter and get 3 distinct movie options based on difficulty and selected languages
 */
export function getMovieChoices(difficulty = 'easy', languages = ['Bollywood'], usedTitles = new Set()) {
    let pool = [];

    if (difficulty === 'easy') {
        const lang = languages[0] || 'Bollywood';
        pool = moviesDatabase.filter(m => m.language.toLowerCase() === lang.toLowerCase() && m.difficulty === 'easy');
    } else if (difficulty === 'medium') {
        const selectedLangs = languages.length > 0 ? languages.map(l => l.toLowerCase()) : ['bollywood', 'hollywood'];
        pool = moviesDatabase.filter(m => 
            selectedLangs.includes(m.language.toLowerCase()) && 
            (m.difficulty === 'medium' || m.difficulty === 'easy')
        );
    } else {
        // Hard: all languages, medium & hard difficulties
        pool = moviesDatabase.filter(m => m.difficulty === 'hard' || m.difficulty === 'medium');
    }

    if (pool.length === 0) {
        pool = [...moviesDatabase];
    }

    // Filter out already used titles if possible
    let available = pool.filter(m => !usedTitles.has(m.title.toLowerCase()));
    if (available.length < 3) {
        available = pool;
    }

    const shuffled = [...available].sort(() => Math.random() - 0.5);
    return shuffled.slice(0, 3).map(m => {
        const words = m.wordCount || (m.title ? m.title.trim().split(/\s+/).length : 1);
        return {
            title: m.title,
            name: m.title,
            language: m.language,
            year: m.year,
            years: m.year,
            wordCount: words,
            countOfWords: words
        };
    });
}

/**
 * Normalizes movie titles and guesses for fair comparison
 */
export function normalizeTitle(str) {
    if (!str) return '';
    return str
        .toLowerCase()
        .replace(/['".,!?:;\-_()]/g, '') // remove punctuation
        .replace(/\s+/g, ' ')            // normalize spaces
        .trim();
}

/**
 * Generate a masked representation of the movie title (e.g. "Dangal" -> "_ _ _ _ _ _")
 */
export function maskTitle(title) {
    if (!title) return '';
    return title.split('').map(char => {
        if (/[a-zA-Z0-9]/.test(char)) return '_';
        if (char === ' ') return '   ';
        return char;
    }).join(' ');
}
